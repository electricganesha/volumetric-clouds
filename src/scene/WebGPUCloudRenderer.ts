import * as THREE from 'three';
import { getWebGPUDevice } from '../noise/WebGPUNoiseGenerator';
import cloudComputeWgsl from '../shaders/cloudCompute.wgsl?raw';

// Double-buffered read slots: while slot A's compute is in-flight,
// slot B's readback is completing — so the GPU never idles.
interface ReadSlot {
  colorBuf: GPUBuffer;
  distBuf: GPUBuffer;
  pendingPromise: Promise<void> | null;
  inFlight: boolean;
}

export class WebGPUCloudRenderer {
  device: GPUDevice | null = null;
  pipeline: GPUComputePipeline | null = null;
  bindGroup: GPUBindGroup | null = null;
  uniformBuffer: GPUBuffer | null = null;

  outColorTexture: GPUTexture | null = null;
  outDistanceTexture: GPUTexture | null = null;

  baseNoiseTexture: GPUTexture | null = null;
  detailNoiseTexture: GPUTexture | null = null;
  weatherMapTexture: GPUTexture | null = null;

  sampler: GPUSampler | null = null;

  // Two read slots for ping-pong readback
  readSlots: [ReadSlot | null, ReadSlot | null] = [null, null];
  currentWriteSlot: 0 | 1 = 0;    // slot currently being dispatched into
  currentReadSlot:  0 | 1 = 1;    // slot whose readback we process this frame

  width: number = 0;
  height: number = 0;
  isAvailable: boolean = false;

  // If setNoiseTextures is called before init() resolves, buffer here.
  private _pendingNoise: { base: ArrayBuffer; detail: ArrayBuffer; weather: ArrayBuffer } | null = null;

  // DataTextures for Three.js
  colorTexture: THREE.DataTexture;
  distanceTexture: THREE.DataTexture;

  private destroyOldResources() {
    if (this.outColorTexture) { this.outColorTexture.destroy(); this.outColorTexture = null; }
    if (this.outDistanceTexture) { this.outDistanceTexture.destroy(); this.outDistanceTexture = null; }
    if (this.uniformBuffer) { this.uniformBuffer.destroy(); this.uniformBuffer = null; }
    for (let i = 0; i < 2; i++) {
      if (this.readSlots[i]) {
        this.readSlots[i]!.colorBuf.destroy();
        this.readSlots[i]!.distBuf.destroy();
        this.readSlots[i] = null;
      }
    }
  }

  constructor(width: number, height: number) {
    this.width = width;
    this.height = height;
    this.colorTexture   = this._makeColorTex(width, height);
    this.distanceTexture = this._makeDistTex(width, height);
  }

  private _makeColorTex(w: number, h: number) {
    const t = new THREE.DataTexture(new Uint8Array(w * h * 4), w, h, THREE.RGBAFormat);
    t.type = THREE.UnsignedByteType;
    t.minFilter = THREE.LinearFilter;
    t.magFilter = THREE.LinearFilter;
    return t;
  }

  private _makeDistTex(w: number, h: number) {
    const t = new THREE.DataTexture(new Uint16Array(w * h * 4), w, h, THREE.RGBAFormat);
    t.type = THREE.HalfFloatType;
    t.minFilter = THREE.NearestFilter;
    t.magFilter = THREE.NearestFilter;
    return t;
  }

  async setSize(width: number, height: number) {
    if (this.width === width && this.height === height) return;
    this.width = width;
    this.height = height;
    this.colorTexture   = this._makeColorTex(width, height);
    this.distanceTexture = this._makeDistTex(width, height);
    if (this.device) await this.init();
  }

  // Dummy textures use ALL ZEROS → weather.r = 0 → coverage = 0 → no clouds visible
  // while the real noise textures are being generated by the worker.
  private _dummy3D(device: GPUDevice): GPUTexture {
    const tex = device.createTexture({
      size: [1, 1, 1], dimension: '3d', format: 'rgba8unorm',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    device.queue.writeTexture({ texture: tex }, new Uint8Array([0, 0, 0, 0]),
      { bytesPerRow: 4, rowsPerImage: 1 }, [1,1,1]);
    return tex;
  }

  private _dummy2D(device: GPUDevice): GPUTexture {
    const tex = device.createTexture({
      size: [1, 1, 1], dimension: '2d', format: 'rgba8unorm',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    device.queue.writeTexture({ texture: tex }, new Uint8Array([0, 0, 0, 0]),
      { bytesPerRow: 4 }, [1,1,1]);
    return tex;
  }

  setNoiseTextures(base: ArrayBuffer, detail: ArrayBuffer, weather: ArrayBuffer) {
    // If the WebGPU device isn't ready yet, buffer the data and apply in init().
    if (!this.device) {
      this._pendingNoise = { base, detail, weather };
      return;
    }

    if (this.baseNoiseTexture)   this.baseNoiseTexture.destroy();
    if (this.detailNoiseTexture) this.detailNoiseTexture.destroy();
    if (this.weatherMapTexture)  this.weatherMapTexture.destroy();

    this.baseNoiseTexture = this.device.createTexture({
      size: [128, 128, 128], dimension: '3d', format: 'rgba8unorm',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    this.device.queue.writeTexture(
      { texture: this.baseNoiseTexture }, base,
      { bytesPerRow: 128 * 4, rowsPerImage: 128 }, [128, 128, 128]);

    this.detailNoiseTexture = this.device.createTexture({
      size: [64, 64, 64], dimension: '3d', format: 'rgba8unorm',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    this.device.queue.writeTexture(
      { texture: this.detailNoiseTexture }, detail,
      { bytesPerRow: 64 * 4, rowsPerImage: 64 }, [64, 64, 64]);

    this.weatherMapTexture = this.device.createTexture({
      size: [256, 256, 1], dimension: '2d', format: 'rgba8unorm',
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
    });
    this.device.queue.writeTexture(
      { texture: this.weatherMapTexture }, weather,
      { bytesPerRow: 256 * 4 }, [256, 256, 1]);

    this.rebuildBindGroup();
  }

  rebuildBindGroup() {
    if (!this.device || !this.pipeline || !this.uniformBuffer ||
        !this.outColorTexture || !this.outDistanceTexture || !this.sampler) return;

    const base    = this.baseNoiseTexture    || this._dummy3D(this.device);
    const detail  = this.detailNoiseTexture  || this._dummy3D(this.device);
    const weather = this.weatherMapTexture   || this._dummy2D(this.device);

    this.bindGroup = this.device.createBindGroup({
      layout: this.pipeline.getBindGroupLayout(0),
      entries: [
        { binding: 0, resource: { buffer: this.uniformBuffer } },
        { binding: 1, resource: this.outColorTexture.createView() },
        { binding: 2, resource: this.outDistanceTexture.createView() },
        { binding: 3, resource: base.createView() },
        { binding: 4, resource: detail.createView() },
        { binding: 5, resource: weather.createView() },
        { binding: 6, resource: this.sampler },
      ],
    });
  }

  async init() {
    this.device = await getWebGPUDevice();
    if (!this.device) {
      this.isAvailable = false;
      return;
    }

    this.destroyOldResources();

    const module = this.device.createShaderModule({ code: cloudComputeWgsl });

    this.pipeline = this.device.createComputePipeline({
      layout: 'auto',
      compute: { module, entryPoint: 'main' },
    });

    this.uniformBuffer = this.device.createBuffer({
      size: 320,
      usage: GPUBufferUsage.UNIFORM | GPUBufferUsage.COPY_DST,
    });

    this.outColorTexture = this.device.createTexture({
      size: [this.width, this.height, 1], format: 'rgba8unorm',
      usage: GPUTextureUsage.STORAGE_BINDING | GPUTextureUsage.COPY_SRC,
    });

    this.outDistanceTexture = this.device.createTexture({
      size: [this.width, this.height, 1], format: 'rgba16float',
      usage: GPUTextureUsage.STORAGE_BINDING | GPUTextureUsage.COPY_SRC,
    });

    this.sampler = this.device.createSampler({
      magFilter: 'linear', minFilter: 'linear',
      addressModeU: 'repeat', addressModeV: 'repeat', addressModeW: 'repeat',
    });

    // Create two read-slot pairs for double-buffered readback
    const bpr_c = Math.ceil((this.width * 4) / 256) * 256;
    const bpr_d = Math.ceil((this.width * 8) / 256) * 256;

    for (let i = 0; i < 2; i++) {
      this.readSlots[i] = {
        colorBuf: this.device.createBuffer({
          size: bpr_c * this.height,
          usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
        }),
        distBuf: this.device.createBuffer({
          size: bpr_d * this.height,
          usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
        }),
        pendingPromise: null,
        inFlight: false,
      };
    }

    this.rebuildBindGroup();

    if (this._pendingNoise) {
      const { base, detail, weather } = this._pendingNoise;
      this._pendingNoise = null;
      this.setNoiseTextures(base, detail, weather);
    }

    this.isAvailable = true;
  }

  /** 
   * Called every frame. The flow is:
   * 1. Check if the *other* slot (currentReadSlot) has finished its mapAsync → copy pixels.
   * 2. Dispatch the new compute frame into currentWriteSlot.
   * 3. Submit + kick off mapAsync for writeSlot (non-blocking).
   * 4. Swap slots.
   *
   * This means there is always one frame of latency, but the GPU stays fully
   * utilised and the main render loop is never stalled.
   */
  tickFrame(
    camera: THREE.PerspectiveCamera,
    time: number,
    jitterX: number,
    jitterY: number,
    cloudMaterial: THREE.ShaderMaterial,
  ) {
    if (!this.device || !this.pipeline || !this.bindGroup || !this.uniformBuffer) return;

    const bpr_c = Math.ceil((this.width * 4) / 256) * 256;
    const bpr_d = Math.ceil((this.width * 8) / 256) * 256;

    const writeSlot = this.readSlots[this.currentWriteSlot];
    const readSlot  = this.readSlots[this.currentReadSlot];

    // --- Step 1: Pull results from the READ slot if its async is done ---
    if (readSlot && readSlot.inFlight && readSlot.pendingPromise) {
      // We can't await here (sync frame), so we check if the buffers are already mapped
      // by attempting to get the mapped range. If mapAsync resolved, state is 'mapped'.
      try {
        const colorMapped = readSlot.colorBuf.getMappedRange();
        const distMapped  = readSlot.distBuf.getMappedRange();

        const colorSrc = new Uint8Array(colorMapped);
        const distSrc  = new Uint8Array(distMapped);

        const colorDst = this.colorTexture.image.data as Uint8Array;
        const distDst  = new Uint8Array((this.distanceTexture.image.data as Uint16Array).buffer);

        for (let y = 0; y < this.height; y++) {
          colorDst.set(colorSrc.subarray(y * bpr_c, y * bpr_c + this.width * 4), y * this.width * 4);
          distDst.set(distSrc.subarray(y * bpr_d, y * bpr_d + this.width * 8), y * this.width * 8);
        }

        this.colorTexture.needsUpdate    = true;
        this.distanceTexture.needsUpdate = true;

        readSlot.colorBuf.unmap();
        readSlot.distBuf.unmap();
        readSlot.inFlight = false;
        readSlot.pendingPromise = null;
      } catch {
        // buffers not yet mapped — will pick up next frame
      }
    }

    // --- Step 2: Guard — don't re-dispatch into writeSlot if its readback is still in flight ---
    if (writeSlot && writeSlot.inFlight) return;
    if (!writeSlot) return;

    // --- Step 3: Build uniforms and dispatch ---
    const u = cloudMaterial.uniforms;
    const uData = new Float32Array(80);

    uData[0] = camera.position.x;
    uData[1] = camera.position.y;
    uData[2] = camera.position.z;
    uData[3] = time;

    uData[4] = u.uSunDirection.value.x;
    uData[5] = u.uSunDirection.value.y;
    uData[6] = u.uSunDirection.value.z;
    uData[7] = u.uCloudCoverage.value;

    uData[8]  = u.uSunColor.value.r;
    uData[9]  = u.uSunColor.value.g;
    uData[10] = u.uSunColor.value.b;
    uData[11] = u.uCloudScale.value;

    uData[12] = u.uZenithColor.value.r;
    uData[13] = u.uZenithColor.value.g;
    uData[14] = u.uZenithColor.value.b;
    uData[15] = u.uDetailScale.value;

    uData[16] = u.uHorizonColor.value.r;
    uData[17] = u.uHorizonColor.value.g;
    uData[18] = u.uHorizonColor.value.b;
    uData[19] = u.uDensityMultiplier.value;

    uData[20] = u.uGroundBounceColor.value.r;
    uData[21] = u.uGroundBounceColor.value.g;
    uData[22] = u.uGroundBounceColor.value.b;
    uData[23] = u.uAnisotropy.value;

    uData[24] = u.uWindVector.value.x;
    uData[25] = u.uWindVector.value.y;
    uData[26] = u.uWindVector.value.z;
    uData[27] = u.uWarpStrength.value;

    uData[28] = u.uBoxMin.value.x;
    uData[29] = u.uBoxMin.value.y;
    uData[30] = u.uBoxMin.value.z;
    uData[31] = u.uForwardGlow.value;

    uData[32] = u.uBoxMax.value.x;
    uData[33] = u.uBoxMax.value.y;
    uData[34] = u.uBoxMax.value.z;
    uData[35] = u.uShadowIntensity.value;

    uData[36] = this.width;
    uData[37] = this.height;
    uData[38] = jitterX;
    uData[39] = jitterY;

    uData[40] = u.uPowderIntensity.value;
    uData[41] = u.uShadowAbsorption.value;
    uData[42] = u.uShadowSoftness.value;
    uData[43] = u.uLightStepLength.value;

    uData[44] = u.uWindShear.value;
    uData[45] = u.uMorphSpeed.value;
    uData[46] = 0.0;
    uData[47] = 0.0;

    const viewInv = camera.matrixWorld.elements;
    for (let i = 0; i < 16; i++) uData[48 + i] = viewInv[i];
    const projInv = camera.projectionMatrixInverse.elements;
    for (let i = 0; i < 16; i++) uData[64 + i] = projInv[i];

    this.device.queue.writeBuffer(this.uniformBuffer, 0, uData);

    const encoder = this.device.createCommandEncoder();
    const pass = encoder.beginComputePass();
    pass.setPipeline(this.pipeline);
    pass.setBindGroup(0, this.bindGroup);
    pass.dispatchWorkgroups(Math.ceil(this.width / 8), Math.ceil(this.height / 8), 1);
    pass.end();

    // Copy output textures → writeSlot readback buffers
    encoder.copyTextureToBuffer(
      { texture: this.outColorTexture! },
      { buffer: writeSlot.colorBuf, bytesPerRow: bpr_c },
      [this.width, this.height, 1],
    );
    encoder.copyTextureToBuffer(
      { texture: this.outDistanceTexture! },
      { buffer: writeSlot.distBuf, bytesPerRow: bpr_d },
      [this.width, this.height, 1],
    );

    this.device.queue.submit([encoder.finish()]);

    // --- Step 4: Kick off non-blocking mapAsync ---
    writeSlot.inFlight = true;
    writeSlot.pendingPromise = Promise.all([
      writeSlot.colorBuf.mapAsync(GPUMapMode.READ),
      writeSlot.distBuf.mapAsync(GPUMapMode.READ),
    ]).then(() => { /* resolved; tickFrame will unmap on next pass */ });

    // Swap write/read slots for next frame
    this.currentWriteSlot = this.currentReadSlot;
    this.currentReadSlot  = (this.currentReadSlot === 0 ? 1 : 0) as 0 | 1;
  }
}
